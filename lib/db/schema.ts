import type { InferSelectModel } from 'drizzle-orm';
import {
  pgTable,
  varchar,
  timestamp,
  json,
  uuid,
  text,
  primaryKey,
  foreignKey,
  boolean,
  integer,
  bigint,
  date,
  numeric,
  unique,
  index,
} from 'drizzle-orm/pg-core';

export const user = pgTable('User', {
  id: uuid('id').primaryKey().notNull().defaultRandom(),
  email: varchar('email', { length: 64 }).notNull(),
  password: varchar('password', { length: 64 }),
});

export type User = InferSelectModel<typeof user>;

export const ledger = pgTable(
  'ledger',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    owner: uuid('owner')
      .notNull()
      .references(() => user.id),
    kind: text('kind', { enum: ['income', 'expense'] }).notNull(),
    description: text('description').notNull(),
    cents: bigint('cents', { mode: 'number' }).notNull(),
    booked: date('booked').notNull(),
    sample: text('sample'),
  },
  (t) => ({ samples: unique('ledger_owner_sample_key').on(t.owner, t.sample) }),
);

export const aiPolicy = pgTable('ai_policy', {
  id: integer('id').primaryKey(),
  dailyLimit: integer('daily_limit'),
});
export const aiCall = pgTable(
  'ai_call',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    started: timestamp('started', { withTimezone: true })
      .notNull()
      .defaultNow(),
    model: text('model').notNull(),
    input: integer('input'),
    output: integer('output'),
    usd: numeric('usd'),
  },
  (t) => ({ startedIndex: index('ai_call_started').on(t.started) }),
);

export const chat = pgTable('Chat', {
  id: uuid('id').primaryKey().notNull().defaultRandom(),
  createdAt: timestamp('createdAt').notNull(),
  title: text('title').notNull(),
  userId: uuid('userId')
    .notNull()
    .references(() => user.id),
  visibility: varchar('visibility', { enum: ['public', 'private'] })
    .notNull()
    .default('private'),
});

export type Chat = InferSelectModel<typeof chat>;

