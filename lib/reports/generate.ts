import type { Transaction } from '@/lib/db/schema';
import {
  formatMoney,
  formatTransactionDate,
} from '@/lib/finance/validation';
import { summarizeTransactions } from '@/lib/finance/summary-client';

export type ReportInput = {
  title?: string;
  transactions: Array<Transaction>;
  generatedAt?: Date;
};

function categoryBreakdown(transactions: Array<Transaction>) {
  const grouped = new Map<string, number>();

  for (const item of transactions) {
    const key = `${item.type === 'income' ? 'Income' : 'Expense'} · ${item.category}`;
    grouped.set(key, (grouped.get(key) ?? 0) + item.amount);
  }

  return [...grouped.entries()].sort((a, b) => b[1] - a[1]);
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function buildReportHtml({
  title = 'Income & Expenses Report',
  transactions,
  generatedAt = new Date(),
}: ReportInput): string {
  const totals = summarizeTransactions(transactions);
  const categories = categoryBreakdown(transactions);

  const rows = transactions
    .map(
      (item) => `        <tr>
          <td>${escapeHtml(formatTransactionDate(item.date))}</td>
          <td>${escapeHtml(item.type)}</td>
          <td>${escapeHtml(item.category)}</td>
          <td>${escapeHtml(item.description)}</td>
          <td class="amount ${item.type}">${
            item.type === 'income' ? '+' : '-'
          }${escapeHtml(formatMoney(item.amount))}</td>
        </tr>`,
    )
    .join('\n');

  const categoryRows = categories
    .map(
      ([name, amount]) =>
        `        <li><span>${escapeHtml(name)}</span><strong>${escapeHtml(
          formatMoney(amount),
        )}</strong></li>`,
    )
    .join('\n');

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>${escapeHtml(title)}</title>
  <style>
    * { box-sizing: border-box; }
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif; margin: 0; padding: 40px; color: #18181b; }
    h1 { font-size: 24px; margin: 0 0 4px; }
    h2 { font-size: 16px; margin: 32px 0 12px; }
    .meta { color: #71717a; font-size: 13px; margin-bottom: 24px; }
    .cards { display: flex; gap: 16px; flex-wrap: wrap; }
    .card { border: 1px solid #e4e4e7; border-radius: 10px; padding: 16px 20px; min-width: 160px; }
    .card span { display: block; color: #71717a; font-size: 12px; text-transform: uppercase; letter-spacing: .05em; }
    .card strong { display: block; margin-top: 6px; font-size: 22px; }
    .income { color: #059669; }
    .expense { color: #dc2626; }
    table { width: 100%; border-collapse: collapse; font-size: 13px; }
    th, td { text-align: left; padding: 8px 10px; border-bottom: 1px solid #e4e4e7; }
    th { background: #f4f4f5; font-size: 11px; text-transform: uppercase; letter-spacing: .04em; color: #52525b; }
    td.amount { text-align: right; font-variant-numeric: tabular-nums; }
    ul { padding: 0; list-style: none; columns: 2; }
    li { display: flex; justify-content: space-between; padding: 6px 0; border-bottom: 1px solid #f4f4f5; font-size: 13px; }
    footer { margin-top: 32px; color: #a1a1aa; font-size: 11px; }
    @media print { body { padding: 0; } .card, tr { break-inside: avoid; } }
  </style>
</head>
<body>
  <h1>${escapeHtml(title)}</h1>
  <div class="meta">Generated ${escapeHtml(
    generatedAt.toISOString().replace('T', ' ').slice(0, 19),
  )} UTC · ${totals.count} transactions · USD</div>

  <div class="cards">
    <div class="card"><span>Total income</span><strong class="income">${escapeHtml(
      formatMoney(totals.incomeCents),
    )}</strong></div>
    <div class="card"><span>Total expenses</span><strong class="expense">${escapeHtml(
      formatMoney(totals.expenseCents),
    )}</strong></div>
    <div class="card"><span>Net balance</span><strong>${escapeHtml(
      formatMoney(totals.balanceCents),
    )}</strong></div>
  </div>

  <h2>By category</h2>
  <ul>
${categoryRows || '        <li>No data</li>'}
  </ul>

  <h2>Transactions</h2>
  <table>
    <thead><tr><th>Date</th><th>Type</th><th>Category</th><th>Description</th><th style="text-align:right">Amount</th></tr></thead>
    <tbody>
${rows || '        <tr><td colspan="5">No transactions yet.</td></tr>'}
    </tbody>
  </table>

  <footer>Generated by the AI Chatbot finance feature · amounts in USD.</footer>
</body>
</html>`;
}

/**
 * A tiny, dependency-free PDF writer. It emits a valid PDF 1.4 document with
 * Helvetica/Courier text and automatic pagination — enough for a readable
 * report without adding a heavy PDF library to the app.
 */
export function buildReportPdf({
  title = 'Income & Expenses Report',
  transactions,
  generatedAt = new Date(),
}: ReportInput): Uint8Array {
  const totals = summarizeTransactions(transactions);
  const categories = categoryBreakdown(transactions);

  const escapePdfText = (value: string) =>
    value
      .replace(/[^\x20-\x7e]/g, '?')
      .replace(/\\/g, '\\\\')
      .replace(/\(/g, '\\(')
      .replace(/\)/g, '\\)');

  type Line = { text: string; font: 'F1' | 'F2' | 'F3'; size: number; color?: string };
  const lines: Array<Line> = [];
  const add = (text: string, font: Line['font'] = 'F1', size = 10, color?: string) =>
    lines.push({ text: text.slice(0, 110), font, size, color });

  add(title, 'F2', 18, '0.05 0.35 0.25 rg');
  add(
    `Generated ${generatedAt.toISOString().replace('T', ' ').slice(0, 19)} UTC | ${
      totals.count
    } transactions | USD`,
    'F1',
    9,
    '0.45 0.45 0.45 rg',
  );
  add('');
  add(`Total income:   ${formatMoney(totals.incomeCents)}`, 'F2', 12, '0.05 0.45 0.3 rg');
  add(`Total expenses: ${formatMoney(totals.expenseCents)}`, 'F2', 12, '0.7 0.15 0.15 rg');
  add(`Net balance:    ${formatMoney(totals.balanceCents)}`, 'F2', 12);
  add('');
  add('BY CATEGORY', 'F2', 12);
  for (const [name, amount] of categories) {
    add(`${name}: ${formatMoney(amount)}`, 'F1', 10);
  }
  add('');
  add('TRANSACTIONS', 'F2', 12);
  add('DATE        TYPE     CATEGORY         DESCRIPTION                              AMOUNT', 'F3', 8);
  add('-'.repeat(100), 'F3', 8);
  for (const item of transactions) {
    const date = formatTransactionDate(item.date);
    const amount = `${item.type === 'income' ? '+' : '-'}${formatMoney(item.amount)}`;
    add(
      `${date.padEnd(12)}${item.type.padEnd(9)}${item.category
        .slice(0, 15)
        .padEnd(17)}${item.description.slice(0, 38).padEnd(40)}${amount}`,
      'F3',
      8,
    );
  }
  if (transactions.length === 0) {
    add('No transactions yet.', 'F1', 10);
  }

  // Reserve the catalog and pages objects; they are filled in once the page
  // count is known.
  const objects: string[] = ['', ''];
  const addObject = (body: string): number => {
    objects.push(body);
    return objects.length;
  };

  const pageIds: number[] = [];
  const linesPerPage = 60;
  for (let i = 0; i < lines.length; i += linesPerPage) {
    const pageLines = lines.slice(i, i + linesPerPage);
    const commands: string[] = ['0.1 0.1 0.1 rg', 'BT'];

    pageLines.forEach((line, index) => {
      const y = 742 - index * 12;
      commands.push(
        `${line.color ?? '0.1 0.1 0.1 rg'}`,
        `/${line.font} ${line.size} Tf`,
        `1 0 0 1 44 ${y} Tm`,
        `(${escapePdfText(line.text)}) Tj`,
      );
    });
    commands.push('ET');

    const stream = `${commands.join('\n')}\n`;
    const contentId = addObject(
      `<< /Length ${Buffer.byteLength(stream, 'latin1')} >>\nstream\n${stream}endstream`,
    );
    pageIds.push(
      addObject(
        `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 5 0 R /F2 6 0 R /F3 7 0 R >> >> /Contents ${contentId} 0 R >>`,
      ),
    );
  }

  objects[0] = '<< /Type /Catalog /Pages 2 0 R >>';
  objects[1] = `<< /Type /Pages /Kids [${pageIds
    .map((id) => `${id} 0 R`)
    .join(' ')}] /Count ${pageIds.length} >>`;
  addObject('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
  addObject('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>');
  addObject('<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>');

  let document = '%PDF-1.4\n';
  const offsets: number[] = [0];
  objects.forEach((body, index) => {
    offsets.push(Buffer.byteLength(document, 'latin1'));
    document += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });

  const xrefOffset = Buffer.byteLength(document, 'latin1');
  document += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i <= objects.length; i += 1) {
    document += `${offsets[i].toString().padStart(10, '0')} 00000 n \n`;
  }
  document += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;

  return new TextEncoder().encode(document);
}
