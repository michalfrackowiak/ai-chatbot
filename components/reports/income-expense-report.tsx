export function generatePDFBase64(report: IncomeExpenseReport): string {
  const html = generateIncomeExpenseHTML(report);
  
  // For now, return a data URI that references the HTML
  // In production, use a proper HTML-to-PDF library like pdf-lib, pdfmake, etc.
  return `data:text/html;base64,${Buffer.from(generateIncomeExpenseHTML(report)).toString('base64')}`;
}