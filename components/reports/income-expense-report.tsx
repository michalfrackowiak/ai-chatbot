import { Income, Expense } from '@/lib/db/schema';
import { getIncomesByUserId, getExpensesByUserId } from '@/lib/db/queries';
import { calculateTotal, calculateNet } from '@/lib/utils';

export interface IncomeExpenseReport {
  incomes: Income[];
  expenses: Expense[];
  totalIncome: number;
  totalExpenses: number;
  net: number;
}

export async function getIncomeExpenseReport(userId: string): Promise<IncomeExpenseReport> {
  const [incomes, expenses] = await Promise.all([
    getIncomesByUserId({ userId }),
    getExpensesByUserId({ userId }),
  ]);

  const totalIncome = calculateTotal(incomes.map(i => i.amount));
  const totalExpenses = calculateTotal(expenses.map(e => e.amount));
  const net = calculateNet(totalIncome, totalExpenses);

  return {
    incomes,
    expenses,
    totalIncome,
    totalExpenses,
    net,
  };
}

